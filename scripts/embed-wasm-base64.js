import fs from "node:fs";
const wasmPath = new URL("../build/math.wasm", import.meta.url);
const jsPath = new URL("../build/math.js", import.meta.url);
if (!fs.existsSync(wasmPath)) throw new Error(`embed-wasm-base64: missing ${wasmPath}`);
if (!fs.existsSync(jsPath)) throw new Error(`embed-wasm-base64: missing ${jsPath}`);
const wasmB64 = fs.readFileSync(wasmPath).toString("base64");
const CHUNK = 1024;
const chunks = [];
for (let i = 0; i < wasmB64.length; i += CHUNK) chunks.push(wasmB64.slice(i, i + CHUNK));
const START = "/*__WASMGPU_EMBED_WASM_BASE64_START__*/";
const END = "/*__WASMGPU_EMBED_WASM_BASE64_END__*/";
const embed = `${START}
// Auto-generated by ./scripts/embed-wasm-base64.js
const __WASMGPU_WASM_BASE64__ = [
${chunks.map((c) => `  ${JSON.stringify(c)},`).join("\n")}
].join("");
const __wasmgpu_base64ToBytes = (b64) => {
    if (typeof atob === "function") {
        const bin = atob(b64);
        const out = new Uint8Array(bin.length);
        for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i) & 255;
        return out;
    }
    if (typeof Buffer !== "undefined") {
        return Uint8Array.from(Buffer.from(b64, "base64"));
    }
    throw new Error("__wasmgpu_base64ToBytes: no base64 decoder available.");
};
${END}`;
const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
let js = fs.readFileSync(jsPath, "utf8");
const blockRe = new RegExp(`${escapeRegExp(START)}[\\s\\S]*?${escapeRegExp(END)}`);
if (blockRe.test(js)) js = js.replace(blockRe, embed);
else js = `${embed}\n\n${js}`;
const nodeNeedle = 'if (isNodeOrBun) { return globalThis.WebAssembly.compile(await (await import("node:fs/promises")).readFile(url)); }';
const webNeedle = 'else { return await globalThis.WebAssembly.compileStreaming(globalThis.fetch(url)); }';
if (!js.includes(nodeNeedle)) throw new Error("embed-wasm-base64: did not find expected Node/Bun loader line in ./build/math.js (AssemblyScript output changed?)");
if (!js.includes(webNeedle)) throw new Error("embed-wasm-base64: did not find expected web browser loader line in ./build/math.js (AssemblyScript output changed?)");
const nodeReplacement =
    'if (isNodeOrBun) {\n' +
    '      try {\n' +
    '        return await globalThis.WebAssembly.compile(await (await import("node:fs/promises")).readFile(url));\n' +
    '      } catch (e) {\n' +
    '        return await globalThis.WebAssembly.compile(__wasmgpu_base64ToBytes(__WASMGPU_WASM_BASE64__));\n' +
    '      }\n' +
    '    }';
const webReplacement =
    'else {\n' +
    '      try {\n' +
    '        return await globalThis.WebAssembly.compileStreaming(globalThis.fetch(url));\n' +
    '      } catch (e) {\n' +
    '        return await globalThis.WebAssembly.compile(__wasmgpu_base64ToBytes(__WASMGPU_WASM_BASE64__));\n' +
    '      }\n' +
    '    }';
js = js.replace(nodeNeedle, nodeReplacement).replace(webNeedle, webReplacement);
fs.writeFileSync(jsPath, js, "utf8");
console.log(`Embedded ./build/math.wasm (${fs.statSync(wasmPath).size} bytes) into ./build/math.js as base64 (${wasmB64.length} chars).`);
